// Safe CSS selector helper that supports jQuery/Playwright-style :contains(...) and :has-text(...)
// and never throws a DOMException SyntaxError on invalid or unescaped selectors.
const nativeDocQuerySelector = typeof Document !== 'undefined' ? Document.prototype.querySelector : null;
const nativeElQuerySelector = typeof Element !== 'undefined' ? Element.prototype.querySelector : null;
const nativeDocQuerySelectorAll = typeof Document !== 'undefined' ? Document.prototype.querySelectorAll : null;
const nativeElQuerySelectorAll = typeof Element !== 'undefined' ? Element.prototype.querySelectorAll : null;

function safeQuerySelector(selectorRaw: string, root: Document | Element = document): HTMLElement | null {
    const sel = (selectorRaw || '').trim();
    if (!sel) return null;

    // Handle :contains("...") or :has-text("...") pseudo-selectors frequently generated by LLMs
    const containsMatch = sel.match(/^(.*?):(contains|has-text)\(\s*(['"]?)([\s\S]*?)\3\s*\)(.*)$/i);
    if (containsMatch) {
        const baseSelector = (containsMatch[1] || '*').trim() || '*';
        const needle = (containsMatch[4] || '').trim().toLowerCase();
        let candidates: HTMLElement[] = [];
        try {
            const rawList = root instanceof Document && nativeDocQuerySelectorAll
                ? nativeDocQuerySelectorAll.call(root, baseSelector)
                : root instanceof Element && nativeElQuerySelectorAll
                ? nativeElQuerySelectorAll.call(root, baseSelector)
                : [];
            candidates = Array.from(rawList) as HTMLElement[];
        } catch {
            const fallbackList = root instanceof Document && nativeDocQuerySelectorAll
                ? nativeDocQuerySelectorAll.call(root, 'button, a, input, [role="button"], span, div, label, li, h1, h2, h3, h4, p')
                : root instanceof Element && nativeElQuerySelectorAll
                ? nativeElQuerySelectorAll.call(root, 'button, a, input, [role="button"], span, div, label, li, h1, h2, h3, h4, p')
                : [];
            candidates = Array.from(fallbackList) as HTMLElement[];
        }
        if (!needle) return candidates[0] || null;
        return (
            candidates.find(el => (el.innerText || el.textContent || '').trim().toLowerCase() === needle) ||
            candidates.find(el => (el.getAttribute('aria-label') || '').trim().toLowerCase() === needle) ||
            candidates.find(el => (el.getAttribute('title') || '').trim().toLowerCase() === needle) ||
            candidates.find(el => ((el as HTMLInputElement).value || '').trim().toLowerCase() === needle) ||
            candidates.find(el => (el.innerText || el.textContent || '').toLowerCase().includes(needle)) ||
            null
        );
    }

    try {
        if (root instanceof Document && nativeDocQuerySelector) {
            return nativeDocQuerySelector.call(root, sel) as HTMLElement | null;
        }
        if (root instanceof Element && nativeElQuerySelector) {
            return nativeElQuerySelector.call(root, sel) as HTMLElement | null;
        }
        return null;
    } catch {
        return null;
    }
}

if (typeof Document !== 'undefined' && !(Document.prototype as any).__nexusSafeQueryPatched) {
    Document.prototype.querySelector = function (selector: string): Element | null {
        try {
            return nativeDocQuerySelector ? nativeDocQuerySelector.call(this, selector) : null;
        } catch {
            return safeQuerySelector(selector, this);
        }
    };
    Element.prototype.querySelector = function (selector: string): Element | null {
        try {
            return nativeElQuerySelector ? nativeElQuerySelector.call(this, selector) : null;
        } catch {
            return safeQuerySelector(selector, this);
        }
    };
    Document.prototype.querySelectorAll = function (selector: string): NodeListOf<Element> {
        try {
            return nativeDocQuerySelectorAll ? nativeDocQuerySelectorAll.call(this, selector) : ([] as any);
        } catch {
            return nativeDocQuerySelectorAll ? nativeDocQuerySelectorAll.call(this, 'nonexistent-nexus-selector') : ([] as any);
        }
    };
    Element.prototype.querySelectorAll = function (selector: string): NodeListOf<Element> {
        try {
            return nativeElQuerySelectorAll ? nativeElQuerySelectorAll.call(this, selector) : ([] as any);
        } catch {
            return nativeElQuerySelectorAll ? nativeElQuerySelectorAll.call(this, 'nonexistent-nexus-selector') : ([] as any);
        }
    };
    (Document.prototype as any).__nexusSafeQueryPatched = true;
}

